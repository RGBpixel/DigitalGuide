async function rights(panel:Locator,label:string){await panel.getByRole('textbox',{name:'授权主体',exact:true}).fill('原创虚构制作人');await panel.getByRole('textbox',{name:'用途及权利说明',exact:true}).fill('仅供本地原生验证的原创参数角色和独立用途授权，不涉及真实人物。');await panel.getByRole('checkbox',{name:label,exact:true}).check();}
async function posted<T>(page:Page,suffix:string,action:()=>Promise<void>):Promise<T>{const pending=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith(suffix)&&r.request().method()==='POST');void pending.catch(()=>{});await action();const response=await pending;assert.equal(response.ok(),true,(await response.text()).slice(0,500));return(await response.json()).data as T;}
