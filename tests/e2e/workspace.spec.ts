import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { syntheticPng } from '@digitalguide/media';

test('管理员完成素材上传、授权、模拟训练、角色保存与刷新恢复', async ({ page }) => {
  const consoleErrors: string[] = [];
  page.on('pageerror', error => consoleErrors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: /林知 · 管理员/ }).click();
  await expect(page.getByRole('heading', { name: '工作空间总览' })).toBeVisible();
  await page.getByRole('link', { name: '资产与角色', exact: true }).click();
  await page.getByRole('button', { name: '上传素材', exact: true }).click();
  const modal = page.getByRole('dialog');
  await modal.getByLabel('选择素材文件').setInputFiles({ name: 'synthetic-demo.png', mimeType: 'image/png', buffer: syntheticPng() });
  const name = '自动验证 · 合成形象';
  await modal.getByLabel('素材名称').fill(name);
  await modal.getByRole('button', { name: '校验并保存素材' }).click();
  await expect(modal).not.toBeVisible();
  await expect(page.getByRole('heading', { name })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name })).toBeVisible();
  await page.getByRole('button', { name: '管理 ' + name }).click();
  await modal.getByLabel('授权主体').fill('虚构测试主体');
  await modal.getByLabel('授权证明说明').fill('本素材为代码生成的合成示例，仅用于本地流程验证。');
  await modal.getByLabel('授权到期时间').fill('2027-12-31T23:59');
  await modal.getByRole('checkbox').check();
  await modal.getByRole('button', { name: '保存授权记录' }).click();
  await expect(modal.getByRole('button', { name: '模拟训练', exact: true })).toBeVisible();
  await modal.getByRole('button', { name: '模拟训练', exact: true }).click();
  await expect(modal.getByRole('status')).toContainText('模拟任务已入队');
  await modal.getByRole('button', { name: '关闭' }).click();
  await page.getByRole('link', { name: '任务中心', exact: true }).click();
  await expect(page.getByText('模拟完成', { exact: true }).first()).toBeVisible();
  await page.getByRole('link', { name: '资产与角色', exact: true }).click();
  await page.getByRole('button', { name: '新建角色' }).click();
  await modal.getByLabel('角色名称').fill('测试讲解员 · 合成');
  await modal.getByLabel('形象参考').selectOption({ label: name });
  await modal.getByRole('checkbox', { name: '视频创作', exact: true }).check();
  await modal.getByRole('button', { name: '保存角色配置' }).click();
  await expect(modal).not.toBeVisible();
  await page.getByRole('button', { name: /数字角色/ }).click();
  await page.getByRole('button', { name: /测试讲解员 · 合成/ }).click();
  await modal.getByRole('button', { name: '检查素材、有效期与提供商' }).click();
  await expect(modal.getByText('模拟场景绑定检查完成。此参考素材不是真实数字人模型。')).toBeVisible();
  await modal.getByRole('button', { name: '关闭' }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: '测试讲解员 · 合成' })).toBeVisible();
  await page.getByRole('link', { name: '总览', exact: true }).click();
  await expect(page.getByRole('heading', { name: '工作空间总览' })).toBeVisible();
  const evidenceDir = process.env.EVIDENCE_DIR || 'docs/evidence/latest';
  mkdirSync(evidenceDir, { recursive: true });
  await page.screenshot({ path: evidenceDir + '/workspace-desktop.png', fullPage: true });
  expect(consoleErrors).toEqual([]);
});
test('只读账号显示权限边界；小屏布局无横向溢出', async ({ page }) => {
  await page.goto('/'); await page.getByRole('button', { name: /许宁 · 只读成员/ }).click();
  await page.getByRole('link', { name: '资产与角色', exact: true }).click();
  await expect(page.getByRole('button', { name: '上传素材', exact: true })).toHaveCount(0);
  await expect(page.getByText(/当前为只读成员/)).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: '资产与角色', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: '打开导航' }).click();
  await page.getByRole('link', { name: '总览', exact: true }).click();
  await expect(page.getByRole('heading', { name: '工作空间总览' })).toBeVisible();
  await expect(page.locator('.sidebar')).not.toHaveClass(/open/);
  await expect.poll(() => page.locator('.sidebar').evaluate(el => Math.round(el.getBoundingClientRect().right))).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: (process.env.EVIDENCE_DIR || 'docs/evidence/latest') + '/workspace-mobile.png', fullPage: true });
});
