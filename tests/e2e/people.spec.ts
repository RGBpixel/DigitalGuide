const evidence = process.env.EVIDENCE_DIR || 'docs/evidence/latest';
async function enroll(panel: ReturnType<Page['getByRole']>, name: string) {
  await panel.getByLabel('希望怎样称呼您', { exact: true }).fill(name);
  await panel.getByRole('checkbox', { name: /我同意保存本人资料/ }).check();
  await panel.getByRole('button', { name: '自愿建立本人资料', exact: true }).click();
  await expect(panel.getByLabel('显示称呼', { exact: true })).toHaveValue(name);
}
