test('独立匿名访客自愿登记，已确认偏好参与回复，删除后对话与偏好清除', async ({ page, context, browser }) => {
  await page.goto('/'); await page.getByRole('button', { name: /林知 · 管理员/ }).click();
  const terminalsLoaded = page.waitForResponse(r => r.url().includes('/api/v1/terminals?') && r.status() === 200);
  await page.getByRole('link', { name: '企业接待', exact: true }).click();
  await terminalsLoaded;
  await expect(page.getByText('正在加载终端…', { exact: true })).not.toBeVisible();
  if (!await page.getByRole('button', { name: '保存终端配置' }).isVisible()) await page.getByText('新增终端', { exact: true }).click();
  await page.getByRole('button', { name: '保存终端配置' }).click();
  await page.getByRole('button', { name: '开始文字接待' }).click();
  await expect(page.getByRole('heading', { name: '您好，欢迎来访' })).toBeVisible();
  const guestContext = await browser.newContext();
  try {
    await guestContext.addCookies((await context.cookies()).filter(c => c.name === 'dg_guest'));
    const guest = await guestContext.newPage(); await guest.goto(page.url());
    const panel = guest.getByRole('region', { name: '我的接待偏好', exact: true });
    await enroll(panel, '虚构来客 · 无登录权限');
    await panel.getByLabel('本人声明', { exact: true }).fill('演示喜欢温水');
    await panel.getByRole('combobox', { name: '使用范围', exact: true }).selectOption('reception');
    await panel.getByRole('button', { name: '添加待确认记忆', exact: true }).click();
    await panel.getByRole('button', { name: '核对并确认记忆', exact: true }).click();
    await panel.getByRole('checkbox', { name: '允许个性化接待', exact: true }).check();
    await panel.getByRole('button', { name: '保存资料与交流设置', exact: true }).click();
    await guest.getByLabel('输入您的问题', { exact: true }).fill('记得我的偏好吗');
    await guest.getByRole('button', { name: '发送文字', exact: true }).click();
    await expect(guest.getByLabel('本次会话消息').getByText(/您已确认并允许本场所使用的资料/)).toContainText('演示喜欢温水');
    await guest.reload(); await expect(panel.getByLabel('显示称呼')).toHaveValue('虚构来客 · 无登录权限');
    await guest.screenshot({ path: evidence + '/guest-memory-desktop.png', fullPage: true });
    await panel.getByRole('checkbox', { name: /确认删除本人资料/ }).check();
    await panel.getByRole('button', { name: '删除本人资料与记忆', exact: true }).click();
    await expect(panel.getByText('本人资料已删除', { exact: true })).toBeVisible();
    await expect(guest.getByLabel('本次会话消息').getByText(/演示喜欢温水/)).toHaveCount(0);
    await guest.getByRole('button', { name: '结束本次接待', exact: true }).click();
  } finally { await guestContext.close(); }
});

